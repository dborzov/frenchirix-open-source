// French strings: the source of truth for the keys. en.ts must have exactly the same keys.
//
// RULES
// - Every user-visible string goes through t(). No literal text in components.
// - French is simple, friendly and short, for a ten-year-old: tutoyer ("Tu as gagné !"), short
//   sentences, no jargon. Typographic French: a non-breaking space before ! ? : ; and inside « » (use " ").
// - One word per concept, the same in every string. The glossary's words (AGENTS.md: pratique /
//   practice, défi / puzzle, niveau / level, quêtes du jour / daily quests, scènes au choix / scenes
//   to choose from, débloquer / unlock, rejouer / replay, série / streak...), and also: réplique /
//   line, touche / tap (never « tape » or « appuie »), micro / mic, appareil / device (not « tablette »:
//   kids play on phones too), code (secret) / (secret) number for the PIN, mot magique / magic word
//   for the school's password. « Rejouer » is only the replay of a practice; for audio, « Réécouter ».
//   Karaoke: chanson / song, enregistrement / recording (only the kid's kept singing of a song), ton
//   chant / your singing (what the mic just captured, before it is kept: never « prise » / "take",
//   words for code and docs only), garder / keep (only the act of making it the recording: never
//   « enregistrer », which means to record), effacer / erase (a recording), jeter / throw away (singing
//   not kept).
// - Comic sound words are French here and English in en.ts: PAF / POW, BOUM / BOOM, TCHAC / SNAP,
//   WAOUH / WOW, OUPS / OOPS, HEIN / HUH, RATÉ / NOPE; BRAVO, BING, BONG and SUPER are the same in both.
// - Tests never look for this text: they use data-* attributes, or translate() from this module.
// - Keys are 'namespace.name'. Each area owns its namespace and adds keys only inside its own
//   section below, so agents working in parallel do not collide:
//     common.  nav.  home.  unlock.  practice.  puzzles.<type>.  scene.  episodes.  karaoke.
//     profile.  avatar.  shop.  chest.  social.  league.  achievements.  login.  version.  dev.
// - Variables: '{name}'. Plurals: 'singular|plural' chosen by the variable `n`
//   (French: n < 2 is singular; English: n === 1 is singular).
// - English glosses of scene content are data, not strings: they never go through t().

